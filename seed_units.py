# ============================================================
# اتصال به دیتابیس
# ============================================================

conn = sqlite3.connect(DATABASE)

cursor = conn.cursor()


# ============================================================
# اطمینان از وجود جدول
# ============================================================

cursor.execute("""
CREATE TABLE IF NOT EXISTS standards (

    id INTEGER PRIMARY KEY AUTOINCREMENT,

    category TEXT NOT NULL,

    code TEXT,

    name TEXT,

    standard TEXT,

    size TEXT,

    description TEXT

)
""")


# ============================================================
# حذف رکوردهای قبلی تبدیل واحد
# ============================================================

cursor.execute("""
DELETE FROM standards
WHERE category = 'units'
""")


# ============================================================
# درج داده‌ها
# ============================================================

for item in units:

    cursor.execute("""
        INSERT INTO standards
        (
            category,
            code,
            name,
            standard,
            size,
            description
        )

        VALUES (?, ?, ?, ?, ?, ?)
    """, (
        "units",
        item["code"],
        item["name"],
        item["standard"],
        item["size"],
        item["description"]
    ))


conn.commit()


# ============================================================
# نمایش نتیجه
# ============================================================

count = cursor.execute("""
    SELECT COUNT(*)
    FROM standards
    WHERE category = 'units'
""").fetchone()[0]


conn.close()


print("====================================")
print("واحدها با موفقیت وارد شدند")
print(f"تعداد رکوردهای تبدیل واحد: {count}")
print("====================================")
