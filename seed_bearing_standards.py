records = []


def add_records(data, bearing_type, standard_name):

    for code, dimensions in data.items():

        bore = dimensions[0]
        outer = dimensions[1]
        width = dimensions[2]

        records.append(
            (
                "bearings",
                code,
                code,
                standard_name,
                f"{bore} × {outer} × {width}",
                bore,
                outer,
                width,
                None,
                "mm",
                "Bearing Steel",
                None,
                None,
                None,
                f"{bearing_type} {code} - ابعاد استاندارد: قطر داخلی d={bore} mm، قطر خارجی D={outer} mm، عرض B={width} mm"
            )
        )


add_records(
    deep_groove,
    "بلبرینگ شیار عمیق",
    "ISO 15"
)

add_records(
    angular,
    "بلبرینگ تماس زاویه‌ای",
    "ISO 15"
)

add_records(
    cylindrical,
    "رولبرینگ استوانه‌ای",
    "ISO 15"
)

add_records(
    tapered,
    "رولبرینگ مخروطی",
    "ISO 355"
)


