# اتصال به دیتابیس
# =========================================================

conn = sqlite3.connect(DATABASE)

cursor = conn.cursor()


# =========================================================
# حذف رکوردهای قبلی برینگ
# =========================================================

cursor.execute("""
DELETE FROM standards
WHERE category = 'bearings'
""")


# =========================================================
# درج اطلاعات
# =========================================================

cursor.executemany("""

INSERT INTO standards
(
    category,
    code,
    name,
    standard,
    size,
    dimension_1,
    dimension_2,
    dimension_3,
    dimension_4,
    unit,
    material,
    property_class,
    value,
    value_2,
    description
)

VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)

""", records)


conn.commit()


